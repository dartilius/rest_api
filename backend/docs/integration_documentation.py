BROADCAST_ORDER_CREATE_DESCRIPTION = _markdown(
    """
    Создаёт заказы фона или рекламы для одной или нескольких точек.

    | Поле | Обязательно | Назначение |
    |---|---:|---|
    | **`name`** | да | Название заказа |
    | **`description`** | нет | Комментарий |
    | **`type`** | да | `bg` — фон; `ad` — реклама |
    | **`clients`** | да | Непустой массив UUID номенклатур; для одной точки массив из одного UUID |
    | **`playlist`** | да | UUID готового плейлиста |
    | **`broadcast_interval`** | для рекламы | `lower` и `upper`: локальные дата/время без часового пояса |
    | **`broadcast_type`** | нет, по умолчанию 0 | Правило рекламы 0–7; для фона не задаётся |
    | **`is_permanent`** | нет | Бессрочный резервный фон без даты окончания |
    | **`parameters`** | зависит от правила | Частота, вес, дни, часы, звук и время фоновых картинок |
    | **`audio_images`** | нет, только реклама | UUID аудио из плейлиста → упорядоченный массив UUID картинок |

    Сервер создаёт одну
    запись для каждой точки и возвращает массив в порядке UUID запроса, даже
    для одного элемента. Повторы UUID и неверные общие параметры отклоняют запрос.
    Каждая точка обрабатывается независимо: заказ и его команда сохраняются вместе.
    Неизвестная, неактивная или несовместимая точка не мешает остальным.

    **Ответ:** массив в порядке UUID из **clients**. Успешный элемент — созданный
    заказ. Отказ — **client** (UUID номенклатуры) и **error** (причина).
    **HTTP 201** — созданы все заказы; **HTTP 207** — созданы только некоторые;
    **HTTP 400** — общая ошибка запроса или ни одна точка не приняла заказ.
    При частичном успехе повторно отправляйте только неуспешные UUID:
    повтор всего списка создаст новые заказы и для уже успешных точек.

    Пример отказа одной точке:

    ```json
    {"client": "5778e050-454d-4e5e-ae0f-bb584979552d", "error": "Player этой точки не поддерживает выбранный функционал. Обновите Player."}
    ```

    ```json
    {
      "name": "Осенняя акция в магазинах сети",
      "type": "ad",
      "clients": [
        "00000000-0000-0000-0000-000000000101",
        "00000000-0000-0000-0000-000000000102"
      ],
      "playlist": "00000000-0000-0000-0000-000000000201",
      "broadcast_interval": {
        "lower": "2026-10-13 09:00:00",
        "upper": "2026-11-01 18:00:00"
      },
      "broadcast_type": 0,
      "parameters": {"times_in_hour": 4, "weekdays": [0, 1, 2, 3, 4]}
    }
    ```

    ### Картинки к рекламному аудио

    Поле **`audio_images`** задаётся на верхнем уровне заказа, рядом с **`playlist`**.
    Ключ — UUID аудио из выбранного плейлиста, значение — массив UUID картинок:

    ```json
    {
      "audio_images": {
        "00000000-0000-0000-0000-000000000011": [
          "00000000-0000-0000-0000-000000000021",
          "00000000-0000-0000-0000-000000000022"
        ]
      }
    }
    ```

    **Как читать конструкцию:** ключ `00000000-0000-0000-0000-000000000011` —
    UUID конкретного аудиофайла из **`files`** выбранного плейлиста. UUID `...021`
    и `...022` внутри массива — файлы картинок именно этого аудиоролика.
    Для другого аудио добавьте другой ключ с его UUID и собственный массив картинок.
    Берите UUID из поля **`id`** файла, а не название, URL или UUID плейлиста.
    Порядок элементов массива определяет порядок показа картинок.

    **`additionalProp1`**, **`additionalProp2`** в автоматически созданных примерах
    документации — заглушки произвольных ключей JSON-объекта. Их нельзя отправлять
    как имена: вместо них указывайте UUID аудиофайлов, как в примере выше.
    UUID примера замените на идентификаторы реально загруженных файлов.

    Это фрагмент запроса: при создании также передайте обязательные поля заказа.
    В ответе возвращается такая же карта UUID, без дублирования URL файлов.
    Загруженные изображения можно найти через `GET /api/files/?file_type=2&name=...`;
    используйте их **`id`**, а **`url`** файла — для предпросмотра.
    Одна картинка показывается всё аудио; несколько делят его длительность
    поровну. Время вручную задавать не нужно. Картинки не требуется добавлять
    в **`files`** плейлиста: Player получает их вместе с заказом.
    Новые привязки требуют активных файлов; ключи должны быть аудио, значения —
    изображениями. Повторы картинок у одного аудио запрещены. Допускается до
    1000 аудио и суммарно 10 000 ссылок на картинки.

    ### Правила рекламы **`broadcast_type`**

    | Значение | Назначение | Обязательные **`parameters`** |
    |---|---|---|
    | **`0`** | В рабочее время точки | **`times_in_hour`** |
    | **`1`** | От открытия со смещением | **`times_in_hour`**, **`timedelta`** |
    | **`2`** | До закрытия со смещением | **`times_in_hour`**, **`timedelta`** |
    | **`3`** | Между фиксированными часами | **`times_in_hour`**, **`start_time`**, **`end_time`** |
    | **`4`** | От открытия до заданного часа | **`times_in_hour`**, **`end_time`** |
    | **`5`** | От заданного часа до закрытия | **`times_in_hour`**, **`start_time`** |
    | **`6`** | По событию | Зарезервировано; пока не использовать |
    | **`7`** | Непрерывная реклама вместо фона | Частота не нужна |

    Для начала с заданного часа используйте **`broadcast_type=5`** и
    **`parameters.start_time`**. Период дат дополнительно ограничивает окно.
    Для фона частота и
    числовое рекламное правило не требуются; тип медиа **`order_type`** вычисляется
    из плейлиста и возвращается только для чтения.

    ### Параметры

    | Поле | Значение | Назначение |
    |---|---|---|
    | **`times_in_hour`** | Целое 1–60 | Число выходов рекламного заказа за час |
    | **`weight`** | Целое 0–100, default 50 | Приоритет очередности, не частота |
    | **`weekdays`** | Разные целые 0–6 | 0 — пн, 1 — вт, 2 — ср, 3 — чт, 4 — пт, 5 — сб, 6 — вс; без поля ежедневно |
    | **`audio_muted`** | true/false | Отключить звук самого рекламного ролика |
    | **`image_duration_seconds`** | Целое 1–86400 | Время фоновой картинки; рекламные картинки синхронизируются с аудио автоматически |
    | **`start_time`**, **`end_time`** | HH:MM:SS | Часы правила |
    | **`timedelta`** | HH:MM:SS | Смещение от открытия/закрытия |

    Период дат действует дополнительно к выбранным местным календарным дням.
    Пустые списки, повторы и значения вне 0–6 отклоняются. Ограничения дней
    доступны также непрерывной рекламе и требуют **`order_schedule_version=1`**
    от Player. Сервер не отправляет такой заказ старому Player молча.

    Бессрочный фон **`is_permanent=true`** остаётся ежедневным резервом. Создайте
    отдельный временный фон с датами и `weekdays`: в подходящее расписание он
    вытесняет резерв своего канала, вне его снова используется резерв. Текущий
    фоновый ролик завершается естественно, следующий выбирается уже по актуальным дням.

    **`suppress_background_audio`** и **`suppress_background_visual`** управляют
    паузой соответствующего фона на время рекламы. Непрерывная реклама всегда
    занимает визуальный канал; фоновая музыка остаётся при **`audio_muted=true`**.
    Эти опции и смешанный визуальный фон проверяются по поддержке Player.

    ### Пересекающийся фон

    Видео и картинки: видео и картинки берутся по одному файлу из каждого
    подходящего временного заказа. Приоритет **`weight`** задаёт очередность:
    A(70) и B(60) → A1, B1, A2, B2. Он не увеличивает частоту. Пока есть временные
    визуальные заказы, бессрочный визуальный резерв не выбирается; текущий файл
    доигрывает перед переключением. У музыки выбирается один временный заказ
    с самой поздней датой начала, **`weight`** на этот выбор сейчас не влияет.

    ### Ответ

    Ответ POST всегда является массивом заказов. В каждом заказе **`clients`** —
    массив объектов **`id`**/**`name`**, **`owner`** — **`id`**/**`full_name`**,
    **`playlist`** — UUID, без
    дублирования файлов и URL плейлиста. **`status=1`** выставляется после первого
    принятого фактического `started` текущей применённой версии, не после создания
    или загрузки. Последующие выходы отражаются в статистике и плане/факте.

    """
)

