"""Reusable Russian Markdown for the 1C control-plane API documentation.

The strings in this module deliberately have no Django imports.  They can be
used by drf-spectacular annotations and by the global schema description
without performing application or database work during import.
"""

from textwrap import dedent


def _markdown(value: str) -> str:
    """Normalize an indented Markdown literal for OpenAPI descriptions."""
    return dedent(value).strip()


ONE_C_INTEGRATION_OVERVIEW = _markdown(
    """
    ## Интеграция 1С: что делает этот API

    1С работает с **контуром управления**: выбирает точку вещания, загружает
    файлы, собирает плейлист и создаёт заказ. Для этих запросов используется
    пользовательский JWT:

    ```http
    Authorization: access_token <JWT>
    Content-Type: application/json
    ```

    Заголовок `access_token` — действующее значение этого проекта. Это не
    стандартный `Bearer`.

    Content Player работает с **контуром станции** и использует другой ключ:

    ```http
    Authorization: Station <station_token>
    ```

    Station token предназначен только для привязанной установки Player и
    обмена `/api/station/v2/sync/` и WebSocket состояния. Его нельзя подставлять вместо JWT в
    запросы 1С. 1С также не должна вызывать старый
    `/api/tasks/{nomenclature_id}/pending_tasks/`: анонимный доступ там сохранён
    только для совместимости со старыми Player.

    Основной сценарий: получить JWT → найти точку по **`code1c`** → загрузить
    файлы → создать плейлист → создать `/api/broadcast-orders/` → читать поля
    **`delivery`** и **`actual_playback`** → при необходимости вызвать
    **`cancel`**.
    """
)


