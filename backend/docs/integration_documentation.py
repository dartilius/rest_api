PLAYLIST_UPDATE_DESCRIPTION = _markdown(
    """
    Частично изменяет плейлист.

    - **`name`** и **`description`** изменяются независимо.
    - Если передано **`items`**, это **полный новый снимок состава**, а не список
      добавлений. Сервер заменяет порядок основных файлов и все связи
      «аудио → картинки» данными из запроса.
    - Если не переданы ни **`items`**, ни **`files`**, состав остаётся прежним.
    - **`files`** заменяет основные файлы. У структурированного плейлиста
      сохранённые аудио сохраняют свои картинки; новые файлы добавляются без них.
    - Нельзя одновременно передавать **`items`** и legacy-поле **`files`**.

    Пример замены состава:

    ```json
    {
      "description": "Новая редакция от 1С",
      "items": [
        {
          "file": "00000000-0000-0000-0000-000000000011",
          "images": ["00000000-0000-0000-0000-000000000023"]
        },
        {
          "file": "00000000-0000-0000-0000-000000000014",
          "images": []
        }
      ]
    }
    ```

    После успешного ответа сохраните возвращённое представление плейлиста как
    актуальное. Не отправляйте только изменённую строку **`items`**: остальные
    строки будут удалены из состава.

    Изменение состава активного единого заказа повышает его **`revision`** и
    создаёт новую команду доставки. Повтор того же состава не создаёт команду.
    Сохранение состава и команд атомарно: ошибка подготовки откатывает всё.
    Полная замена **`items`** или **`files`** при активных старых BgOrder/AdOrder
    запрещена; используйте их прежние add/remove либо отмените старые заказы.
    Пустой состав допускается при PATCH только без активных заказов.
    """
)


