"""Reusable Russian Markdown for the 1C control-plane API documentation.

The strings in this module deliberately have no Django imports.  They can be
used by drf-spectacular annotations and by the global schema description
without performing application or database work during import.
"""

from textwrap import dedent


def _markdown(value: str) -> str:
    """Normalize an indented Markdown literal for OpenAPI descriptions."""
    return dedent(value).strip()


